-- Run this in Supabase SQL Editor.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 40),
  rating integer not null check (rating between 1 and 5),
  text text not null check (char_length(text) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;

revoke all on table public.reviews from anon, authenticated;
grant select, insert on table public.reviews to anon;

create policy "Public can read customer reviews"
on public.reviews for select to anon using (true);

create policy "Public can submit customer reviews"
on public.reviews for insert to anon
with check (char_length(name) between 1 and 40 and rating between 1 and 5 and char_length(text) between 1 and 500);

