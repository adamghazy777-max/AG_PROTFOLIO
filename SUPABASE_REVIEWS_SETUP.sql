-- Global visitor counter (one row per browser/device ID).
create table if not exists public.site_visitors (
  visitor_id text primary key check (char_length(visitor_id) between 10 and 100),
  last_seen timestamptz not null default now()
);

alter table public.site_visitors enable row level security;
revoke all on table public.site_visitors from anon, authenticated;

create or replace function public.register_visit(p_visitor_id text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_visitor_id is null or char_length(p_visitor_id) < 10 or char_length(p_visitor_id) > 100 then
    raise exception 'invalid visitor id';
  end if;
  insert into public.site_visitors(visitor_id,last_seen) values(p_visitor_id,now())
  on conflict (visitor_id) do update set last_seen=now();
  return (select count(*) from public.site_visitors);
end;
$$;

revoke all on function public.register_visit(text) from public, anon, authenticated;
grant execute on function public.register_visit(text) to anon;
